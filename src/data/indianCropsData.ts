/**
 * Unique Crop Categories available across India
 */
export const INDIAN_CROP_CATEGORIES = [
  'All Categories',
  'Cereals & Millets',
  'Plantation Crops',
  'Spices & Condiments',
  'Cash Crops & Fiber',
  'Pulses & Legumes',
  'Oilseeds',
  'Horticulture & Fruits',
  'Vegetables',
] as const;

export type IndianCropCategory = (typeof INDIAN_CROP_CATEGORIES)[number];

export const IndianCropsService = {
  getAllCrops(): IndianCrop[] {
    return INDIAN_PRIMARY_CROPS;
  },

  getCropById(id: string): IndianCrop | undefined {
    return INDIAN_PRIMARY_CROPS.find((c) => c.id === id);
  },

  getCropsByCategory(category: string): IndianCrop[] {
    if (!category || category === 'All Categories') {
      return INDIAN_PRIMARY_CROPS;
    }
    return INDIAN_PRIMARY_CROPS.filter((c) => c.category === category);
  },

  getVarietiesForCrop(cropNameOrId: string) {
    const crop = INDIAN_PRIMARY_CROPS.find(
      (c) =>
        c.id === cropNameOrId ||
        c.name.toLowerCase() === cropNameOrId.toLowerCase() ||
        c.commonName.toLowerCase() === cropNameOrId.toLowerCase() ||
        c.scientificName.toLowerCase() === cropNameOrId.toLowerCase()
    );
    return crop ? crop.varieties : [];
  },

  searchCropsAndVarieties(query: string) {
    const q = query.trim().toLowerCase();
    if (!q) return INDIAN_PRIMARY_CROPS;

    return INDIAN_PRIMARY_CROPS.filter(
      (c) =>
        c.name.toLowerCase().includes(q) ||
        c.commonName.toLowerCase().includes(q) ||
        c.kannadaName.toLowerCase().includes(q) ||
        c.hindiName.toLowerCase().includes(q) ||
        c.scientificName.toLowerCase().includes(q) ||
        c.category.toLowerCase().includes(q) ||
        c.majorGrowingStates.some((st) => st.toLowerCase().includes(q)) ||
        c.varieties.some(
          (v) =>
            v.name.toLowerCase().includes(q) ||
            v.keyFeatures.toLowerCase().includes(q) ||
            (v.specialty && v.specialty.toLowerCase().includes(q))
        )
    );
  },
};
